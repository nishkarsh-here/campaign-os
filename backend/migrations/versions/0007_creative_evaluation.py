"""Milestone 7 — creative evaluation and selection.

Two tables, and the two that are deliberately absent are as much of the design.

**No `evaluation_jobs` table.** An evaluation *is* the unit of work, so its
status lives on `creative_evaluations` itself: `PENDING -> RUNNING ->
COMPLETED | FAILED`, with `payload` null until the work finishes and `error`
set instead when it does not. A second table pointing at this one would add a
join and a way for the two to disagree about the same fact.

**No rankings table.** A ranking is a pure function of the stored evaluations —
score, then brand alignment, then campaign fit, then asset id — so storing one
would create a second source of truth that could fall out of step with the
evaluations it summarises. It is computed on read.

`creative_evaluations` is unique on `(generated_asset_id, evaluator_version)`.
Re-running the same evaluator updates in place; a future `v2` writes a row
beside `v1` rather than over it, which is the entire point of recording a
version — results from different criteria must never be silently compared as
though they were equivalent.

`overall_score` and `disposition` are denormalised out of the payload so
ranking and filtering do not parse JSON. They are only ever written together
with the payload that produced them, and a CHECK keeps the score inside 0-100.

`specification_id` / `specification_version` record the plan the *asset* was
generated from. An asset is always judged against the plan it was actually
given, never against a specification approved afterwards.

`creative_selections` is append-only: a change of mind adds a row and the
current selection is the most recent. `evaluation_id` is nullable on purpose —
a human may overrule the ranking, and the product must let them.

Alembic does not autogenerate CHECK constraints on existing tables but does
emit table-level ones for new tables, so the status, disposition and score
constraints below are real; a regression test proves they reject bad values.
"""

